// Builds functions/_shared/notify_i18n.ts: the translations the SERVER needs for phone notifications.
// It takes every text the server can send (string/template literals in handlers.ts, `${x}` → `{}`) and keeps those
// that the app already translates (app/src/i18n/*.json). Run after adding notification texts:
//   node supabase/scripts/build-notify-i18n.mjs
import { readFileSync, writeFileSync } from 'node:fs'
const root = new URL('../../', import.meta.url).pathname
const src = readFileSync(root + 'supabase/functions/_shared/handlers.ts', 'utf8')
const keys = new Set()
// string literals
for (const m of src.matchAll(/'((?:[^'\\\n]|\\.){0,200})'/g)) keys.add(m[1].replace(/\\'/g, "'"))
for (const m of src.matchAll(/"((?:[^"\\\n]|\\.){0,200})"/g)) keys.add(m[1].replace(/\\"/g, '"'))
// template literals: replace ${...} (with nested braces) by {}
for (let i = 0; i < src.length; i++) {
  if (src[i] !== '`') continue
  let out = '', j = i + 1, ok = true
  while (j < src.length && src[j] !== '`') {
    if (src[j] === '\\') { out += src[j + 1]; j += 2; continue }
    if (src[j] === '$' && src[j + 1] === '{') {
      let depth = 1; j += 2
      while (j < src.length && depth) { if (src[j] === '{') depth++; else if (src[j] === '}') depth--; else if (src[j] === '`') { ok = false; break } j++ }
      out += '{}'; continue
    }
    if (src[j] === '\n') ok = false
    out += src[j]; j++
  }
  if (ok && out.length >= 3 && out.length <= 200) keys.add(out)
  i = j
}
// pieces like `${emoji} ${title}` are split by the server; also try each text without a leading emoji
// texts that start with an emoji ("💸 You received {}") are also looked up without it
for (const k of [...keys]) { const m = /^(\p{Extended_Pictographic}[\u{FE0F}\u{200D}\p{Extended_Pictographic}]*)\s+(.+)$/u.exec(k); if (m) keys.add(m[2]) }
const out = {}
for (const lang of ['fr', 'tr', 'sw', 'ar']) {
  const dict = JSON.parse(readFileSync(root + `app/src/i18n/${lang}.json`, 'utf8'))
  const pick = {}
  for (const k of [...keys].sort()) if (dict[k] !== undefined && /[A-Za-z]/.test(k)) pick[k] = dict[k]
  out[lang] = pick
}
const n = Object.keys(out.fr).length
writeFileSync(root + 'supabase/functions/_shared/notify_i18n.ts',
  `// GENERATED by supabase/scripts/build-notify-i18n.mjs from app/src/i18n/*.json — do not edit by hand.\n` +
  `// Phone notifications are written in English on the server and translated here into the person's language.\n` +
  `export const NOTIFY_I18N: Record<string, Record<string, string>> = ${JSON.stringify(out, null, 0)}\n`)
console.log(`notify_i18n.ts: ${n} texts per language`)
