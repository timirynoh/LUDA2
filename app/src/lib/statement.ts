// Monthly wallet statement (v1.21.0): drawn on canvas pages (A4) and put into a PDF, like the receipts (no library).
// The numbers all come from the server ledger (GET statement); the phone only lays them out.
export interface StatementRow { at: string; cur: string; amount: number; balance: number; kind: string; cat: string; ref: string; who: string | null; note: string | null }
export interface Statement {
  month: string; months: string[]
  currencies: Record<string, { opening: number; closing: number; in: number; out: number }>
  categories: { cat: string; cur: string; in: number; out: number; n: number }[]
  rows: StatementRow[]
  holder: { name: string; username: string; email: string }
}

export const CAT_LABEL: Record<string, [string, string]> = {
  topups: ['💰', 'Top-ups'], transfers: ['💸', 'Transfers'], conversions: ['🔁', 'Conversions'], transport: ['🚌', 'Bus tickets'],
  withdrawals: ['🏦', 'Withdrawals'], bills: ['🧾', 'Bills'], market: ['🛍️', 'Market'], flash: ['⚡', 'Flash'], p2p: ['🤝', 'P2P'],
  savings: ['🐷', 'Savings'], exchanger: ['🏅', 'Exchanger bond'], other: ['🎁', 'Rewards & other'],
}
const KIND_LABEL: Record<string, string> = {
  deposit: 'Top-up', convert: 'Conversion', ticket: 'Bus ticket', ticket_refund: 'Ticket refund', withdraw: 'Withdrawal', withdraw_fee: 'Withdrawal fee',
  withdraw_reversal: 'Withdrawal returned', reward: 'Reward', adjustment: 'Adjustment by Luda', pot_in: 'Moved to savings', pot_out: 'Moved from savings',
  bill_pay: 'Bill payment', bill_refund: 'Bill refund', market_pay: 'Market purchase', market_refund: 'Market refund', market_earn: 'Market sale',
  flash_pay: 'Flash reward', flash_refund: 'Flash refund', flash_earn: 'Flash job paid', p2p_pay: 'P2P (held)', p2p_refund: 'P2P refund', p2p_earn: 'P2P received',
  bond_pay: 'Exchanger bond', bond_refund: 'Exchanger bond returned',
}
export const rowLabel = (r: StatementRow) => r.kind === 'send' ? `Sent to @${r.who ?? ''}` : r.kind === 'receive' ? `Received from @${r.who ?? ''}` : KIND_LABEL[r.kind] ?? r.kind
const SYM: Record<string, string> = { NGN: '₦', TRY: '₺', USD: '$', EUR: '€', GBP: '£' }
export const amt = (minor: number, cur: string, sign = false) => `${sign ? (minor < 0 ? '−' : '+') : minor < 0 ? '−' : ''}${SYM[cur] ?? `${cur} `}${(Math.abs(minor) / 100).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
export const monthName = (m: string) => new Date(`${m}-15T12:00:00Z`).toLocaleDateString('en-GB', { month: 'long', year: 'numeric' })

const W = 1240, H = 1754, PAD = 90
const font = (w: number, s: number) => `${w} ${s}px "Plus Jakarta Sans", system-ui, sans-serif`

function page(n: number, total: () => number, st: Statement) {
  const c = document.createElement('canvas'); c.width = W; c.height = H
  const g = c.getContext('2d')!
  g.fillStyle = '#ffffff'; g.fillRect(0, 0, W, H)
  // header band
  g.fillStyle = '#059669'; g.fillRect(0, 0, W, 14)
  g.fillStyle = '#0b1220'; g.font = font(800, 44); g.fillText('Luda', PAD, 100)
  g.font = font(600, 22); g.fillStyle = '#556274'; g.fillText('Wallet statement', PAD, 138)
  g.textAlign = 'right'; g.fillStyle = '#0b1220'; g.font = font(700, 30); g.fillText(monthName(st.month), W - PAD, 100)
  g.font = font(500, 20); g.fillStyle = '#556274'; g.fillText(`${st.holder.name} · @${st.holder.username}`, W - PAD, 136)
  g.textAlign = 'left'
  // footer
  g.font = font(500, 17); g.fillStyle = '#98a2b3'
  g.fillText('Generated by Luda from its ledger. Times are Cyprus time. Questions? Help → Message us.', PAD, H - 60)
  g.textAlign = 'right'; g.fillText(`Page ${n} of ${total()}`, W - PAD, H - 60); g.textAlign = 'left'
  return { c, g }
}

/** Draws the statement on as many A4 pages as needed. */
export function drawStatement(st: Statement): HTMLCanvasElement[] {
  const pages: HTMLCanvasElement[] = []
  const total = () => pages.length
  let { c, g } = page(1, total, st); pages.push(c)
  let y = 200
  // summary per currency
  for (const [cur, s] of Object.entries(st.currencies)) {
    g.fillStyle = '#f1f4f9'; g.beginPath(); g.roundRect(PAD, y, W - PAD * 2, 120, 22); g.fill()
    g.fillStyle = '#0b1220'; g.font = font(800, 26); g.fillText(cur === 'NGN' ? 'Naira wallet' : cur === 'TRY' ? 'Lira wallet' : cur, PAD + 30, y + 46)
    const cols: [string, string][] = [['Opening', amt(s.opening, cur)], ['Money in', amt(s.in, cur)], ['Money out', amt(s.out, cur)], ['Closing', amt(s.closing, cur)]]
    cols.forEach(([k, v], i) => {
      const x = PAD + 30 + i * ((W - PAD * 2 - 60) / 4)
      g.font = font(500, 18); g.fillStyle = '#6b7686'; g.fillText(k, x, y + 82)
      g.font = font(700, 22); g.fillStyle = k === 'Money in' ? '#047857' : k === 'Money out' ? '#b91c1c' : '#0b1220'; g.fillText(v, x, y + 108)
    })
    y += 146
  }
  if (!Object.keys(st.currencies).length) { g.font = font(500, 22); g.fillStyle = '#556274'; g.fillText('No wallet activity yet.', PAD, y + 30); y += 60 }
  // table
  const head = (yy: number) => {
    g.font = font(700, 18); g.fillStyle = '#6b7686'
    g.fillText('DATE', PAD, yy); g.fillText('DESCRIPTION', PAD + 170, yy)
    g.textAlign = 'right'; g.fillText('AMOUNT', W - PAD - 220, yy); g.fillText('BALANCE', W - PAD, yy); g.textAlign = 'left'
    g.strokeStyle = '#d6dce6'; g.lineWidth = 2; g.beginPath(); g.moveTo(PAD, yy + 14); g.lineTo(W - PAD, yy + 14); g.stroke()
    return yy + 52
  }
  y = head(y + 30)
  if (!st.rows.length) { g.font = font(500, 22); g.fillStyle = '#556274'; g.fillText('No transactions this month.', PAD, y) }
  for (const r of st.rows) {
    if (y > H - 130) { ({ c, g } = page(pages.length + 1, total, st)); pages.push(c); y = head(200) }
    const d = new Date(r.at)
    g.font = font(500, 19); g.fillStyle = '#556274'
    g.fillText(d.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', timeZone: 'Europe/Nicosia' }) + ' ' + d.toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit', timeZone: 'Europe/Nicosia' }), PAD, y)
    g.fillStyle = '#0b1220'; g.font = font(600, 20)
    let label = rowLabel(r); while (g.measureText(label).width > 520 && label.length > 4) label = label.slice(0, -2)
    g.fillText(label, PAD + 170, y)
    g.font = font(500, 15); g.fillStyle = '#98a2b3'; g.fillText(r.ref.slice(-14), PAD + 170, y + 22)
    g.textAlign = 'right'; g.font = font(700, 20); g.fillStyle = r.amount < 0 ? '#b91c1c' : '#047857'; g.fillText(amt(r.amount, r.cur, true), W - PAD - 220, y)
    g.fillStyle = '#0b1220'; g.font = font(500, 19); g.fillText(amt(r.balance, r.cur), W - PAD, y); g.textAlign = 'left'
    g.strokeStyle = '#eef1f5'; g.lineWidth = 1; g.beginPath(); g.moveTo(PAD, y + 36); g.lineTo(W - PAD, y + 36); g.stroke()
    y += 58
  }
  return pages
}

const toJpeg = (c: HTMLCanvasElement) => new Promise<Uint8Array>((ok, no) => c.toBlob((b) => (b ? b.arrayBuffer().then((a) => ok(new Uint8Array(a))) : no(new Error('canvas'))), 'image/jpeg', 0.9))

/** Several canvas pages → one PDF (each page an image), built by hand like the receipts. */
export async function pagesToPdf(pages: HTMLCanvasElement[], title: string): Promise<Blob> {
  const enc = new TextEncoder(), parts: Uint8Array[] = [], offs: number[] = []
  let len = 0
  const push = (b: Uint8Array | string) => { const u = typeof b === 'string' ? enc.encode(b) : b; parts.push(u); len += u.length }
  const obj = (n: number, body: string | (() => void)) => { offs[n] = len; push(`${n} 0 obj\n`); if (typeof body === 'string') push(body); else body(); push('\nendobj\n') }
  const pw = 595, ph = 842 // A4 in points
  const n = pages.length, kids = pages.map((_, i) => `${3 + i * 3} 0 R`).join(' ')
  push('%PDF-1.4\n%\xE2\xE3\xCF\xD3\n')
  obj(1, '<< /Type /Catalog /Pages 2 0 R >>')
  obj(2, `<< /Type /Pages /Kids [${kids}] /Count ${n} >>`)
  for (let i = 0; i < n; i++) {
    const p = 3 + i * 3, jpg = await toJpeg(pages[i]), content = `q ${pw} 0 0 ${ph} 0 0 cm /Im0 Do Q`
    obj(p, `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${pw} ${ph}] /Resources << /XObject << /Im0 ${p + 1} 0 R >> >> /Contents ${p + 2} 0 R >>`)
    obj(p + 1, () => { push(`<< /Type /XObject /Subtype /Image /Width ${pages[i].width} /Height ${pages[i].height} /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length ${jpg.length} >>\nstream\n`); push(jpg); push('\nendstream') })
    obj(p + 2, `<< /Length ${content.length} >>\nstream\n${content}\nendstream`)
  }
  const info = 3 + n * 3
  obj(info, `<< /Title (${title.replace(/[()\\]/g, '')}) /Producer (Luda) >>`)
  const xref = len
  push(`xref\n0 ${info + 1}\n0000000000 65535 f \n${offs.slice(1).map((o) => String(o).padStart(10, '0') + ' 00000 n \n').join('')}trailer\n<< /Size ${info + 1} /Root 1 0 R /Info ${info} 0 R >>\nstartxref\n${xref}\n%%EOF`)
  return new Blob(parts as BlobPart[], { type: 'application/pdf' })
}

/** Builds the PDF and shares it (phones) or downloads it. */
export async function saveStatementPdf(st: Statement): Promise<'shared' | 'downloaded'> {
  const blob = await pagesToPdf(drawStatement(st), `Luda statement ${st.month}`)
  const file = new File([blob], `luda-statement-${st.month}.pdf`, { type: 'application/pdf' })
  try { if (navigator.canShare?.({ files: [file] })) { await navigator.share({ files: [file] }); return 'shared' } } catch (e) { if ((e as { name?: string })?.name === 'AbortError') return 'shared' }
  const url = URL.createObjectURL(file), a = document.createElement('a'); a.href = url; a.download = file.name; document.body.appendChild(a); a.click(); a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 5000)
  return 'downloaded'
}
